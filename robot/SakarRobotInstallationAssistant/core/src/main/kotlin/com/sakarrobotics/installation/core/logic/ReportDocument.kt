package com.sakarrobotics.installation.core.logic

import com.sakarrobotics.installation.core.model.InstallationReport

/** How a line of the exported report should be drawn. The PDF renderer maps these to fonts and colours. */
enum class LineStyle { HEADING, BODY, MUTED, WARNING, ITEM_REQUIRED, ITEM_OPTIONAL }

data class DocLine(val text: String, val style: LineStyle = LineStyle.BODY)

data class DocSection(val title: String, val lines: List<DocLine>)

/**
 * Platform-independent layout model of the installation report. The Android layer only has to draw it
 * into a PDF; everything the report says is decided (and unit-tested) here.
 *
 * It contains the report data only: no device identifiers, no account information, no credentials.
 */
data class ReportDocument(
    val title: String,
    val banner: String,
    val subtitle: String,
    val sections: List<DocSection>,
    val footerNotice: String
) {
    /** Every text line in reading order (used by tests and by the renderer's self-check). */
    fun allText(): List<String> =
        listOf(banner, title, subtitle) + sections.flatMap { s -> listOf(s.title) + s.lines.map { it.text } } +
            footerNotice
}

object ReportDocumentBuilder {

    fun build(report: InstallationReport): ReportDocument {
        val summary = DocSection(
            "Summary",
            listOf(
                DocLine("Installation ID: ${report.installationId}"),
                DocLine("Report ID: ${report.id}"),
                DocLine("Generated: ${ReportBuilder.formatTimestamp(report.generatedAtMillis)}"),
                DocLine("Completion status: ${report.completionStatus ?: ReportBuilder.NOT_RECORDED}"),
                DocLine(report.mappingStatus)
            )
        )

        val floors = DocSection(
            "Floors and simulated maps",
            if (report.floors.isEmpty()) {
                listOf(DocLine("No floors were selected.", LineStyle.MUTED))
            } else {
                report.floors.flatMap { floor ->
                    listOf(DocLine(floor.name)) + if (floor.maps.isEmpty()) {
                        listOf(DocLine("    No saved simulated map", LineStyle.MUTED))
                    } else {
                        floor.maps.map {
                            DocLine(
                                "    Map \"${it.name}\" - ${it.status}, ${it.coveragePercent}% simulated coverage",
                                LineStyle.MUTED
                            )
                        }
                    }
                }
            } + DocLine("Maps are Sakar demo data and are not in any vendor map format.", LineStyle.MUTED)
        )

        val diagnostics = DocSection(
            "Simulated diagnostics",
            listOf(
                DocLine(report.diagnosticsSummary),
                DocLine("No physical sensor was read. All results are generated by the simulation.", LineStyle.MUTED)
            )
        )

        val checklist = DocSection(
            "Checklist results",
            if (report.checklist.isEmpty()) {
                listOf(DocLine("The checklist is empty.", LineStyle.MUTED))
            } else {
                report.checklist.map {
                    val note = if (it.note.isBlank()) "" else " - Note: ${it.note}"
                    DocLine(
                        "[${it.state}] ${it.title} (${if (it.required) "required" else "optional"})$note",
                        if (it.required) LineStyle.ITEM_REQUIRED else LineStyle.ITEM_OPTIONAL
                    )
                }
            }
        )

        val warnings = DocSection(
            "Outstanding warnings",
            if (report.warnings.isEmpty()) {
                listOf(DocLine("None.", LineStyle.MUTED))
            } else {
                report.warnings.map { DocLine("- $it", LineStyle.WARNING) }
            }
        )

        return ReportDocument(
            title = "Installation Report",
            banner = SimulationNotice.PDF_BANNER,
            subtitle = "Sakar Robotics - Robot Installation Assistant",
            sections = listOf(summary, floors, diagnostics, checklist, warnings),
            footerNotice = report.simulationNotice
        )
    }
}
